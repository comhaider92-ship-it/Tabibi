from pathlib import Path
root=Path(__file__).parent
checks=[]
def check(name, ok):
    checks.append((name, bool(ok)))
entity=(root/'src/medical-records/medical-record.entity.ts').read_text()
logs=(root/'src/medical-records/medical-record-access-log.entity.ts').read_text()
service=(root/'src/medical-records/medical-records.service.ts').read_text()
controller=(root/'src/medical-records/medical-records.controller.ts').read_text()
module=(root/'src/medical-records/medical-records.module.ts').read_text()
app=(root/'src/app.module.ts').read_text()
migration=(root/'src/database/migrations/1734200000000-CreatePatientMedicalRecords.ts').read_text()
dto=(root/'src/medical-records/dto/create-medical-record.dto.ts').read_text()
check('medical records entity exists', '@Entity({ name: \'medical_records\' })' in entity)
check('patient ownership indexed', "['patientUserId', 'createdAt']" in entity)
check('soft deletion supported', 'deletedAt' in entity and 'IsNull()' in service)
check('author and role persisted', 'authorUserId' in entity and 'authorRole' in entity)
check('appointment linkage persisted', 'appointmentId' in entity)
check('owner denied medical record access', "actor.role === UserRole.OWNER" in service and 'السجل الطبي غير متاح' in service)
check('doctor access requires appointment', "if (!appointmentId)" in service and "doctorId: actor.sub" in service)
check('doctor sees records only for selected appointment', 'patientUserId: patientId, appointmentId, deletedAt: IsNull()' in service)
check('unregistered beneficiary cannot receive doctor record', 'المستفيد غير مسجل' in service)
check('doctor cannot create record for cancelled/no-show appointment', 'AppointmentStatus.CANCELLED' in service and 'AppointmentStatus.NO_SHOW' in service)
check('doctor can only update own record', 'row.authorUserId !== actor.sub' in service)
check('patient can only delete own patient-authored record', 'row.patientUserId !== actor.sub' in service and 'MedicalRecordAuthorRole.PATIENT' in service)
check('access actions are logged', "'read'" in service and "'create'" in service and "'update'" in service and "'delete'" in service)
check('patient-only access history', "actor.role !== UserRole.PATIENT" in service and 'accessHistory' in controller)
check('API guarded by JWT and role guards', 'JwtAuthGuard, RolesGuard' in controller)
check('DTO validates size and types', 'MaxLength(12000)' in dto and 'IsIn(' in dto)
check('module registered', 'MedicalRecordsModule' in app and 'MedicalRecordAccessLog' in app)
check('migration creates both tables and indexes', 'CREATE TABLE "medical_records"' in migration and 'CREATE TABLE "medical_record_access_logs"' in migration and 'CREATE INDEX' in migration)
check('access log does not store clinical content', 'content' not in logs.lower() and 'title' not in logs.lower())
check('documentation includes migration and limits', 'Run the migration' in (root/'docs/phase-v81-patient-medical-records.md').read_text())
for name,ok in checks:
    print(('PASS' if ok else 'FAIL')+' '+name)
print(f'RESULT {sum(ok for _,ok in checks)}/{len(checks)}')
raise SystemExit(0 if all(ok for _,ok in checks) else 1)
