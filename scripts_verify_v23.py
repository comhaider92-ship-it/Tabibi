from pathlib import Path
root=Path(__file__).resolve().parent
checks=[]
def check(label,ok): checks.append((label,bool(ok)))
svc=(root/'src/facilities/facilities.service.ts').read_text()
ctrl=(root/'src/facilities/facilities.controller.ts').read_text()
slot=(root/'src/facilities/facility-slot.entity.ts').read_text()
booking=(root/'src/facilities/facility-booking.entity.ts').read_text()
dto=(root/'src/facilities/dto/create-facility-booking.dto.ts').read_text()
migration=(root/'src/database/migrations/1732300000000-AddFacilityAvailabilityAndManagement.ts').read_text()
module=(root/'src/facilities/facilities.module.ts').read_text()
app=(root/'src/app.module.ts').read_text(); datasource=(root/'src/database/data-source.ts').read_text()
docs=(root/'docs/phase-v23-facility-scheduling-and-booking-management.md').read_text()
check('availability slot entity defines unique facility/service/start identity','uq_facility_service_slot_start' in slot)
check('slot state is constrained to available, booked or cancelled',all(x in slot for x in ['available','booked','cancelled']))
check('slot creation verifies facility ownership and active service','ownedFacility(ownerId,facilityId)' in svc and 'isActive:true' in svc)
check('slot creation validates future time and service duration','startsAt<=new Date()' in svc and 'duration-service.expectedDurationMinutes' in svc)
check('public slots are only returned for approved facilities','status:FacilityStatus.APPROVED' in svc and 'FacilitySlotStatus.AVAILABLE' in svc)
check('public slot date range is capped at 31 days','31*86400000' in svc)
check('patient booking requires a concrete slot id','slotId:string' in dto)
check('booking locks the slot row inside a transaction','dataSource.transaction' in svc and "setLock('pessimistic_write')" in svc)
check('booking marks the slot booked atomically','slot.status=FacilitySlotStatus.BOOKED' in svc)
check('owner can list bookings for owned facility','ownerBookings' in svc and 'ownedFacility(ownerId,facilityId)' in svc)
check('owner can confirm or reject pending requests','FacilityBookingStatus.CONFIRMED' in svc and 'FacilityBookingStatus.REJECTED' in svc)
check('rejection and patient cancellation release the slot','FacilitySlotStatus.AVAILABLE' in svc)
check('patient cancellation checks booking ownership','booking.bookedByUserId!==userId' in svc)
check('booking status reason is separate from patient note','statusNote' in booking and 'booking.statusNote=dto.reason' in svc)
check('slot entity is registered with runtime and migration data source','FacilityAvailabilitySlot' in app and 'FacilityAvailabilitySlot' in datasource)
check('facility module registers slot repository','FacilityAvailabilitySlot' in module)
check('migration adds slot table, slot reference and rejection status',all(x in migration for x in ['facility_availability_slots','"slotId"','rejected']))
check('controller exposes patient and owner slot/booking endpoints',all(x in ctrl for x in ["@Get(':id/slots')","@Post('owner/:id/slots')","@Get('owner/:id/bookings')","@Patch('owner/bookings/:bookingId/status')","@Patch('bookings/:id/cancel')"]))
check('phase docs explain request confirmation and notification limitation','remain `requested`' in docs and 'not wired' in docs)
for label,ok in checks: print(('PASS' if ok else 'FAIL')+' '+label)
print(f'{sum(ok for _,ok in checks)}/{len(checks)} checks passed')
raise SystemExit(0 if all(ok for _,ok in checks) else 1)
