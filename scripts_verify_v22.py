from pathlib import Path
root=Path(__file__).resolve().parent
checks=[]
def check(label, ok): checks.append((label, bool(ok)))
doctor_dto=(root/'src/doctors/dto/doctor-directory-query.dto.ts').read_text()
doctor_svc=(root/'src/doctors/doctors.service.ts').read_text()
doctor_ctrl=(root/'src/doctors/doctors.controller.ts').read_text()
facility_dto=(root/'src/facilities/dto/facility-directory-query.dto.ts').read_text()
facility_svc=(root/'src/facilities/facilities.service.ts').read_text()
facility_ctrl=(root/'src/facilities/facilities.controller.ts').read_text()
docs=(root/'docs/phase-v22-name-based-search.md').read_text()
check('doctor directory accepts a simple q search parameter', 'q?: string' in doctor_dto)
check('doctor q search matches doctor full name', 'p.fullName ILIKE :searchText' in doctor_svc)
check('doctor q search also matches specialty and clinic name', 'p.specialty ILIKE :searchText' in doctor_svc and 'p.clinicName ILIKE :searchText' in doctor_svc)
check('legacy doctor name filter remains compatible', 'if (filters.name?.trim()) qb.andWhere' in doctor_svc)
check('facility directory accepts q, name, serviceName, city and type', all(f'{x}?: string' in facility_dto for x in ['q','name','serviceName','city','type']))
check('facility search joins active services only', "s.facilityId = f.id AND s.isActive = true" in facility_svc)
check('facility q search matches either facility or service name', 'f.name ILIKE :directorySearch' in facility_svc and 's.name ILIKE :directorySearch' in facility_svc)
check('explicit facility and service name filters are supported', 'facilityName' in facility_svc and 'serviceName' in facility_svc)
check('facility directory remains limited to approved facilities', 'status:FacilityStatus.APPROVED' in facility_svc)
check('public facility results do not expose owner account identifier', "'f.ownerUserId'" not in facility_svc and "'f.id','f.name'" in facility_svc)
check('facility controller binds the validated directory query DTO', '@Query() filters:FacilityDirectoryQueryDto' in facility_ctrl)
check('doctor static routes precede UUID route', doctor_ctrl.index("@Get('me/profile')") < doctor_ctrl.index("@Get(':id')"))
check('search behavior documented for mobile UI', 'q=' in docs and 'اسم الطبيب' in docs and 'اسم المختبر' in docs)
for label,ok in checks: print(('PASS' if ok else 'FAIL')+' '+label)
print(f'{sum(ok for _,ok in checks)}/{len(checks)} checks passed')
raise SystemExit(0 if all(ok for _,ok in checks) else 1)
